package com.hippo.ehviewer.gallerylist

/**
 * Android-free snapshot of the fields of a gallery that the list post-processing
 * (favourite hiding / version folding) needs. Keeping it free of Android types
 * allows the whole pipeline to be unit tested on the JVM.
 */
data class GalleryEntry(
    val gid: Long,
    val title: String?,
    val titleJpn: String? = null,
    /** EhUtils category bit, or [UNKNOWN_CATEGORY]. */
    val category: Int = UNKNOWN_CATEGORY,
    val uploader: String? = null,
    /** Raw E-Hentai tags such as `artist:foo`, `language:chinese`. Null if unknown. */
    val tags: List<String>? = null,
    val pages: Int = 0,
    val rating: Float = 0f,
    /** Simple language code generated by GalleryInfo (EN, ZH, ...). Null for Japanese/unknown. */
    val simpleLanguage: String? = null,
) {
    companion object {
        /** Mirrors EhUtils.UNKNOWN. */
        const val UNKNOWN_CATEGORY = 0x800
    }
}
